import { Type } from '@sinclair/typebox';
import { ELanguage } from '@core/common/enums/ELanguage';
import { ETagSwagger } from '@core/common/enums/ETagSwagger';
import { authForgotPasswordResetPasswordResponseSchema } from './response.schema';
import { authForgotPasswordResetPasswordRequestSchema } from './request.schema';
import { userAttendanceHoursBlockedDataSchema } from '@core/schema/user/attendanceHours/shared.schema';

export const forgotPasswordResetPasswordSchema = {
  description: 'Redefine a senha do usuário após verificação do código',
  tags: [ETagSwagger.auth],
  produces: ['application/json'],
  headers: Type.Object({
    'Accept-Language': Type.Optional(
      Type.String({
        description: 'Idioma preferencial para a resposta',
        enum: Object.values(ELanguage),
        default: ELanguage.pt,
      })
    ),
    Authorization: Type.String({
      description: 'Token JWT temporário obtido após verificação do código',
    }),
  }),
  body: authForgotPasswordResetPasswordRequestSchema,
  response: {
    200: Type.Object(
      {
        id: Type.Optional(Type.Union([Type.String(), Type.Null()])),
        status: Type.Boolean({ const: true }),
        message: Type.String(),
        data: authForgotPasswordResetPasswordResponseSchema,
      },
      { description: 'Successful' }
    ),
    400: Type.Object(
      {
        id: Type.Optional(Type.Union([Type.String(), Type.Null()])),
        status: Type.Boolean({ default: false }),
        message: Type.String(),
        data: Type.Null(),
      },
      { description: 'Bad Request' }
    ),
    403: Type.Object(
      {
        id: Type.Optional(Type.Union([Type.String(), Type.Null()])),
        status: Type.Boolean({ default: false }),
        message: Type.String(),
        data: userAttendanceHoursBlockedDataSchema,
      },
      { description: 'Forbidden' }
    ),
    500: Type.Object(
      {
        id: Type.Optional(Type.Union([Type.String(), Type.Null()])),
        status: Type.Boolean({ default: false }),
        message: Type.String(),
        data: Type.Null(),
      },
      { description: 'Internal Server Error' }
    ),
  },
};
